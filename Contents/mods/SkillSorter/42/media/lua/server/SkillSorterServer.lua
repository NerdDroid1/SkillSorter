local function matchVehiclePartCategory(fullType)
    if not fullType then return nil end
    local short = tostring(fullType):match("%.(.+)$") or tostring(fullType)
    local lower = string.lower(short)
    local hasPart = false
    for _, marker in ipairs(vehiclePartMarkers) do
        if short:find(marker) then hasPart = true; break end
    end
    if not hasPart then return nil end
    -- Most modded vehicle body items start with a year/model code, e.g. 69camaroDoor3.
    if short:find("^%d%d") then return "Mechanics" end
    for _, marker in ipairs(vehicleContextMarkers) do
        if lower:find(marker, 1, true) then return "Mechanics" end
    end
    return nil
end

local function matchPatternCategory(fullType)
    if not fullType then return nil end
    local short = tostring(fullType):match("%.(.+)$") or tostring(fullType)
    for _, rule in ipairs(patternRules) do
        local cat, patterns = rule[1], rule[2]
        for _, pat in ipairs(patterns) do
            if short:find(pat) then return cat end
        end
    end
    return nil
end

local function getCategoryForItem(item)
    if not item then return nil end
    local fullType = item.getFullType and item:getFullType()
    if fullType and SkillSorter.ItemToCategory[fullType] then return SkillSorter.ItemToCategory[fullType] end
    local vehiclePartCat = matchVehiclePartCategory(fullType)
    if vehiclePartCat then return vehiclePartCat end
    local patternCat = matchPatternCategory(fullType)
    if patternCat then return patternCat end
    if fullType and SkillSorter.PZWikiItemCategory and SkillSorter.PZWikiItemCategory[fullType] then return SkillSorter.PZWikiItemCategory[fullType] end
    local displayCategory = item.getDisplayCategory and item:getDisplayCategory()
    if displayCategory and displayCategoryFallback[displayCategory] then return displayCategoryFallback[displayCategory] end
    if displayCategory == "Weapon" and item.isRanged then
        local ok, ranged = pcall(function() return item:isRanged() end)
        if ok then return ranged and "Firearms" or "WeaponsTools" end
    end
    if item.getTags then
        local ok, tags = pcall(function() return item:getTags() end)
        if ok and tags then
            for i = 0, tags:size() - 1 do
                local tag = tostring(tags:get(i))
                if tagFallback[tag] then return tagFallback[tag] end
            end
        end
    end
    return "Misc"
end

local function normalizeSortBinName(name)
    if not name then return nil end
    local value = tostring(name)
    -- Accept forgiving player names:
    --   [Sort:Food], [SORT:food], Sort:Food, sort:food
    --   Food, food, Clothes, Input, input, Dump, dump
    -- Brackets, Sort prefix, spacing, and case are all optional.
    local match = value:match("^%s*%[?%s*[Ss][Oo][Rr][Tt]%s*:%s*([%w]+)%s*%]?%s*$")
    if not match then
        match = value:match("^%s*([%w]+)%s*$")
    end
    if not match then return nil end
    return match:lower()
end

local function getCategoryFromBinName(name)
    local key = normalizeSortBinName(name)
    if not key then return nil end
    return categorySet[key]
end

local function isInputBinName(name)
    local key = normalizeSortBinName(name)
    if not key then return false end
    return categorySet[key] == "Input"
end

local function getContainerSquare(container)
    local parent = container and container.getParent and container:getParent()
    return parent and parent.getSquare and parent:getSquare(), parent
end

local function syncContainer(container)
    if not container then return end
    pcall(function() container:setDrawDirty(true) end)
    local parent = container.getParent and container:getParent()
    if parent then
        pcall(function() parent:sendSyncEntity(nil) end)
        pcall(function() parent:sync() end)
        pcall(function() parent:syncItemFields() end)
    end
end

local function findBinsNear(square)
    local bins = {}
    if not square then return bins end
    local cell = getCell()
    local z, ox, oy = square:getZ(), square:getX(), square:getY()
    local radius = SkillSorter.Config.binRadius
    for x = ox - radius, ox + radius do
        for y = oy - radius, oy + radius do
            local sq = cell:getGridSquare(x, y, z)
            if sq then
                local objects = sq:getObjects()
                for i = 0, objects:size() - 1 do
                    local obj = objects:get(i)
                    local c = obj and obj.getContainer and obj:getContainer()
                    if c then
                        local cat = getCategoryFromBinName(c:getName())
                        if cat then bins[cat] = c end
                    end
                end
            end
        end
    end
    return bins
end

local function routeInputContainer(input)
    local square = getContainerSquare(input)
    if not square then return 0 end
    local bins = findBinsNear(square)
    local moved = 0
    local items = input:getItems()
    for i = items:size() - 1, 0, -1 do
        local item = items:get(i)
        local cat = getCategoryForItem(item)
        local dest = cat and bins[cat]
        if dest and dest ~= input then
            local fullType = item.getFullType and item:getFullType() or tostring(item)
            input:DoRemoveItem(item)
            dest:AddItem(item)
            moved = moved + 1
            log("Routed " .. tostring(fullType) .. " -> " .. cat)
        end
    end
    if moved > 0 then
        syncContainer(input)
        for _, dest in pairs(bins) do syncContainer(dest) end
    end
    return moved
end

local function scanAroundSquare(square)
    if not square then return 0 end
    local cell = getCell()
    local z, ox, oy = square:getZ(), square:getX(), square:getY()
    local radius = SkillSorter.Config.playerScanRadius
    local moved = 0
    local seen = {}
    for x = ox - radius, ox + radius do
        for y = oy - radius, oy + radius do
            local sq = cell:getGridSquare(x, y, z)
            if sq then
                local objects = sq:getObjects()
                for i = 0, objects:size() - 1 do
                    local obj = objects:get(i)
                    local c = obj and obj.getContainer and obj:getContainer()
                    if c and isInputBinName(c:getName()) and not seen[c] then
                        seen[c] = true
                        moved = moved + routeInputContainer(c)
                    end
                end
            end
        end
    end
    return moved
end

function SkillSorter.tick()
    local now = getTimestampMs and getTimestampMs() or 0
    if SkillSorter._nextTick and now < SkillSorter._nextTick then return end
    SkillSorter._nextTick = now + SkillSorter.Config.tickMs
    local moved = 0
    local players = getOnlinePlayers and getOnlinePlayers() or nil
    if players then
        for i = 0, players:size() - 1 do
            local player = players:get(i)
            local square = player and player.getSquare and player:getSquare()
            moved = moved + scanAroundSquare(square)
        end
    end
    if moved > 0 then log("Moved " .. tostring(moved) .. " item(s) this scan") end
end

